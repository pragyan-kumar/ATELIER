function generateReviews(productId, count) {
  const seed = productId * 7;
  const reviews = [];
  for (let i = 0; i < Math.min(count, 6); i++) {
    const idx = (seed + i) % reviewerNames.length;
    const tIdx = (seed + i * 3) % reviewTexts.length;
    const rating = Math.max(3, Math.min(5, 4 + ((seed + i) % 3) - 1));
    reviews.push({
      id: `${productId}-${i}`,
      author: reviewerNames[idx],
      rating,
      text: reviewTexts[tIdx],
      date: `2026-${String(((i + productId) % 12) + 1).padStart(2, '0')}-${String(((i * 3 + productId) % 28) + 1).padStart(2, '0')}`,
    });
  }
  return reviews;
}

